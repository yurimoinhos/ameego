// Command ameego is the installable CLI for the Ameego codegen tool.
//
// Install the binary into $GOPATH/bin or $GOBIN:
//
//	go install github.com/yurimoinhos/ameego/cmd/ameego@latest
//
// Ensure $GOBIN (or $GOPATH/bin) is on your PATH, then run:
//
//	ameego generate
//
// From a module checkout you can also install locally:
//
//	go install ./cmd/ameego
//
