package introspect

import (
	"fmt"
	"sort"
	"strings"

	"github.com/yurimoinhos/ameego/internal/dialect"
	"github.com/yurimoinhos/ameego/internal/schema"
)

// EmitDDL renders a *schema.Schema back into CREATE TABLE statements for the
// given dialect. The output is a valid migration file that, when parsed by the
// migration parser, reproduces the same schema — closing the reverse-engineer
// loop so `generate` stays the single codegen entrypoint.
//
// Column SQL types come straight from the source catalog, so they are already
// dialect-faithful; EmitDDL only frames them in CREATE TABLE/identifier-quoting
// for the target dialect.
func EmitDDL(d dialect.Dialect, s *schema.Schema) string {
	var b strings.Builder
	fmt.Fprintf(&b, "-- Code generated by `ameego introspect`. Review before committing.\n")
	fmt.Fprintf(&b, "-- Dialect: %s\n\n", d.Name())

	// Emit tables in FK-dependency order so references resolve.
	for _, t := range topoSortTables(s.Tables) {
		if t.IsView() {
			continue // views are not reproducible as CREATE TABLE
		}
		emitTable(&b, d, t)
		b.WriteString("\n")
	}
	return b.String()
}

func emitTable(b *strings.Builder, d dialect.Dialect, t schema.Table) {
	fmt.Fprintf(b, "CREATE TABLE %s (\n", d.QuoteIdent(t.Name))

	lines := make([]string, 0, len(t.Columns)+1)
	for _, c := range t.Columns {
		line := "    " + d.QuoteIdent(c.Name) + " " + c.SQLType
		if !c.Nullable {
			line += " NOT NULL"
		}
		if c.Default != "" && !c.IsAutoIncr {
			line += " DEFAULT " + c.Default
		}
		if c.RefTable != "" && c.RefColumn != "" {
			line += fmt.Sprintf(" REFERENCES %s (%s)",
				d.QuoteIdent(c.RefTable), d.QuoteIdent(c.RefColumn))
		}
		lines = append(lines, line)
	}
	if len(t.PrimaryKey) > 0 {
		quoted := make([]string, len(t.PrimaryKey))
		for i, pk := range t.PrimaryKey {
			quoted[i] = d.QuoteIdent(pk)
		}
		lines = append(lines, "    PRIMARY KEY ("+strings.Join(quoted, ", ")+")")
	}

	b.WriteString(strings.Join(lines, ",\n"))
	b.WriteString("\n);\n")
}

// topoSortTables orders tables so a referenced table precedes its referrers.
// Falls back to the original order on cycles (self-referential FKs are fine).
func topoSortTables(tables []schema.Table) []schema.Table {
	index := map[string]int{}
	for i, t := range tables {
		index[strings.ToLower(t.Name)] = i
	}
	deps := make([][]int, len(tables))
	for i, t := range tables {
		seen := map[int]struct{}{}
		for _, c := range t.Columns {
			if c.RefTable == "" {
				continue
			}
			j, ok := index[strings.ToLower(stripSchema(c.RefTable))]
			if !ok || j == i {
				continue
			}
			if _, dup := seen[j]; dup {
				continue
			}
			seen[j] = struct{}{}
			deps[i] = append(deps[i], j)
		}
		sort.Ints(deps[i])
	}

	const (
		white = 0
		gray  = 1
		black = 2
	)
	color := make([]int, len(tables))
	var out []schema.Table
	var visit func(i int) bool
	visit = func(i int) bool {
		if color[i] == black {
			return true
		}
		if color[i] == gray {
			return false // cycle
		}
		color[i] = gray
		for _, j := range deps[i] {
			visit(j)
		}
		color[i] = black
		out = append(out, tables[i])
		return true
	}
	ok := true
	for i := range tables {
		if !visit(i) {
			ok = false
		}
	}
	if !ok || len(out) != len(tables) {
		return tables // cycle detected: preserve catalog order
	}
	return out
}

func stripSchema(name string) string {
	if i := strings.LastIndex(name, "."); i >= 0 {
		return name[i+1:]
	}
	return name
}
